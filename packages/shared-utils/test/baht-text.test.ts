import { bahtText } from '../src/baht-text';

describe('bahtText', () => {
  it.each([
    ['0', 'ศูนย์บาทถ้วน'],
    ['1', 'หนึ่งบาทถ้วน'],
    ['10', 'สิบบาทถ้วน'],
    ['11', 'สิบเอ็ดบาทถ้วน'],
    ['20', 'ยี่สิบบาทถ้วน'],
    ['21', 'ยี่สิบเอ็ดบาทถ้วน'],
    ['101', 'หนึ่งร้อยเอ็ดบาทถ้วน'],
    ['1500', 'หนึ่งพันห้าร้อยบาทถ้วน'],
    ['12345', 'หนึ่งหมื่นสองพันสามร้อยสี่สิบห้าบาทถ้วน'],
    ['1000000', 'หนึ่งล้านบาทถ้วน'],
    ['1000001', 'หนึ่งล้านเอ็ดบาทถ้วน'],
    ['2100000', 'สองล้านหนึ่งแสนบาทถ้วน'],
    ['11000000', 'สิบเอ็ดล้านบาทถ้วน'],
    ['1000000000', 'หนึ่งพันล้านบาทถ้วน'],
    ['9999999999.99', 'เก้าพันเก้าร้อยเก้าสิบเก้าล้านเก้าแสนเก้าหมื่นเก้าพันเก้าร้อยเก้าสิบเก้าบาทเก้าสิบเก้าสตางค์'],
    ['0.50', 'ห้าสิบสตางค์'],
    ['0.01', 'หนึ่งสตางค์'],
    ['21.25', 'ยี่สิบเอ็ดบาทยี่สิบห้าสตางค์'],
    ['100.21', 'หนึ่งร้อยบาทยี่สิบเอ็ดสตางค์'],
    ['-5', 'ลบห้าบาทถ้วน'],
  ])('%s → %s', (input, expected) => {
    expect(bahtText(input)).toBe(expected);
  });
});
